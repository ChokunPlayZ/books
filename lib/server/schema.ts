export async function migrateDatabase(pool: Pool) {
  const client = await pool.connect();
  try {
    await client.query("BEGIN");
    await client.query("SELECT pg_advisory_xact_lock(726004, 0)");
    await client.query(
      "CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP)",
    );
    const result = await client.query(
      "SELECT MAX(version) AS version FROM schema_migrations",
    );
    const version = Number(result.rows[0].version || 0);
    if (version > migrations.length)
      throw new Error("This database needs a newer version of meemai.");
    for (let index = version; index < migrations.length; index++) {
      await client.query(migrations[index]);
      await client.query(
        "INSERT INTO schema_migrations (version) VALUES ($1)",
        [index + 1],
      );
    }
    await client.query("COMMIT");
  } catch (error) {
    await client.query("ROLLBACK");
    throw error;
  } finally {
    client.release();
  }
}
